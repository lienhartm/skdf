<div class="histoire">
    <img src="../media/ferme du roedelen 2.jpg" alt="Ferme du Roedelen" width="200" height="250" class="left" />
    <h3>L'histoire du Ski-Club de 1909 à nos jours.</h3>
    <p>C'est le 9 octobre 1909 que le Ski-Club est crée par le Docteur WUEST et M.Wilhelm WOLFF. Le but de cette
        réunion était au départ de créer une "SKI VEREINIGUNG" pour enseigner un nouveau sport…le ski.</p>
    <p>La première assemblée est organisée le 21 octobre 1909 et le Club Vosgien constate que 27 enthousiastes
        du ski se sont déjà fait inscrire dans cette nouvelle section. Celle-ci grandit très vite et le 4
        décembre 1909 on ne compte pas moins de 40 membres. M. WOLFF, nommé "Ski-Wart", donne des cours
        théoriques. Le 12 décembre 1909, la section se risque à une excursion commune, qui la mène de Lautenbach
        au Grand-Ballon. La randonnée continue après un bon repas vers le Lac de la Lauch, via le Morfeld. Le
        ciel bleu, la mer de brouillard et les beautés hivernales de la nature, spectacle inconnu à tous les
        participants les enthousiasment à tel point que tous prennent la résolution de revenir.</p>
</div>

<div class="histoire">
    <p>Au début de l'hiver 1910, la section s'organise. Le premier comité est élu. Sont nommés :</p>
    <ul>
        <li>Premier Président: M. ATORF</li>
        <li>Second Président: M.WUEST</li>
        <li>Caissier: M.ULRICH</li>
        <li>Hüttenwart: M.BACKERT</li>
        <li>Schriftwart: M.ROTHLEY</li>
    </ul>
</div>

<div class="histoire">
    <img src="../media/numérisation000111_1.jpg" alt="" width="300" height="250" class="right" />
    <p>La cotisation annuelle est fixée à 5 Marks. La ferme du Roedelen est louée moyennant 50 Marks, bois der
        chauffage compris. Une cuisine provisoire est installée, ainsi qu'une chambre avec 4 lits de camp.</p>
    <p>Le 18 Février 1911, les plaisirs d'hiver sont cruellement troublés par le décès de Albert BACKERT, qui
        s'égare dans le mauvais temps et s'endort, épuisé, à seulement 150 mètres de la "Glashütte". Le Ski-Club
        lui a érigé un monument près de la "Glashütte". Cette pierre existe toujours. En automne 1911,
        l'aménagement de la ferme du Roedelen est complété par l'installation d'un fourneau dans la deuxième
        chambre, ainsi que 6 lits en fer. Le premier cours de ski est dirigé par M. FRAUDE.</p>
    <p>Le début de l'été de cette même année voit le 1er feu de la St. Jean au Grand-Ballon. L'expérience étant
        renouvelée en 1913 et 1914.</p>
    <br />
    <p>La saison 1912-1913 voit le comité s'élargir de 5 à 10 membres. Malgré un enneigement médiocre, on se met
        sérieusement à l'entraînement, sous la direction de M. FRICK, LIENHARD et MEYER. Le 16 février 1913, une
        1ère course est organisée sur les pentes du Roedelen, suivie d'une distribution de prix à l'Hôtel de
        l'Ange. Au mois d'avril il est question d'un agrandissement du local dans la ferme et même de la
        construction d'un refuge.</p>
    <p>Le Club adhère à la fédération des Skieurs des Vosges. La décision la plus importante prise lors de
        l'assemblée Générale du 2 juin 1913 est la séparation de la section de ski de sa société mère, par la
        création d'un club autonome sous la désignation "SKI-CLUB GROSSER-BELCHEN-GEBWEILER". Une commission
        rédige les statuts et le règlement du refuge.</p>
    <p>Du 26 au 28 décembre 1913 une course de ski a lieu au Roedelen. M. Jean WETTERWALD est désigné pour
        participer à une course organisée à Davos. Les discussions au sujet d'un agrandissement de la ferme
        reprennent de plus belle. Malheureusement, la guerre survient et ruine tous ces beaux projets...</p>
</div>

<div class="histoire">
    <img src="../media/numérisation002111.jpg" alt="Ferme du Roedelen" width="300" height="250" class="right" />
    <h3>1920-1937: Le premier refuge et les premières compétitions officielles de ski.</h3>
    <p>Une fois la tourmente passée, on se compte et on se regroupe. La première séance d'après-guerre se tient
        le
        20 Novembre 1920 au Canon d'Or, sous la présidence de M. WETTERWALD. La première décision est de s'unir
        à
        nouveau au Club Vosgien, pour former une sous section analogue à la première. La ferme du Roedelen ayant
        été
        détruite au cours des hostilités, le Club Vosgien autorise sa sous-section à utiliser pendant les
        saisons
        d'hiver 1921/22 et 1922/23, les baraques des ouvriers occupés pendant la bonne saison à la construction
        de
        l'Hôtel du Grand-Ballon.</p>
    <p>1922 voit l'admission du 1er membre féminin, Mme Edmond BRITZEL. 39 nouveaux adhérents portent à 80
        l'effectif du club. La vieille tradition du feu de la St. Jean est reprise au Grand-Ballon.</p>
</div>

<div class="histoire">
    <p>Le 25 février 1923 a lieu au Grand-Ballon la première course interne depuis 1913. Durant l'Assemblée
        Générale du 18 février 1923, le Président J. WETTERWALD passe le flambeau à M. MEYER.</p>
    <p>La construction de l'hôtel du Grand-ballon étant achevée et les baraques des ouvriers furent enlevées et
        le club se retrouva sans refuge et sans possibilité de relouer la ferme ni de trouver un autre endroit,
        tous étant déjà occupés par d'autres clubs. N'ayant pas le choix, on décide de rester au Roedelen. Ce
        champ d'exercice offre d'ailleurs de très bonnes conditions d'enneigement et la proximité, à pied, de
        Guebwiller. Après quatre années sans abri, il est décidé de construire un refuge.</p>
</div>

<div class="histoire">
    <img src="../media/numérisation0005.jpg" alt="Travaux de construction du refuge" width="300" height="250"
        class="left" />
    <p>L'architecte qui dresse les plans et dirige les travaux est M. STEMMEL, un membre du club. Les travaux de
        maçonnerie débutent le 16 juillet 1923. C'est le 18 novembre 1923 qu'à lieu l'inauguration du refuge, en
        présence de M. le sous préfet DUROCHER, des délégués de la fédération des skieurs des Vosges, des
        ski-clubs et du Club Vosgien. En 1924 et 1925, l'installation se poursuit. Le 19 août 1924, notre club
        est inscrit au registre des sociétés et acquiert par-là sa personnalité juridique. En janvier 1925, le
        club présente 3 de ses membres au brevet de skieur militaire.</p>
    <p>Le 27 juin, le feu de la St Jean au sommet du Grand-ballon attire une grande foule. Durant l'été les
        journées de travail s'organisent au refuge. Celui-ci connaît une bonne fréquentation puisque 967
        personnes y ont séjourné cette année-là. En hiver 1926, 42 nouvelles adhésions sont enregistrées, le
        club compte 181 membres. Six de nos membres participent cette même année à l'ascension du Mont-Blanc,
        organisée par la Fédération. Cet hiver-là voit les premiers classements en compétition officielle.</p>
</div>

<div class="histoire">
    <p>Les manifestations de l'été connaissent à nouveau une belle affluence. Le Ski-Club grâce aux efforts de
        son Vice-Président Adolphe SCHLUMBERGER, connaît un succès grandissant, le club compte en 1928, 324
        membres dont 46 juniors.</p>
    <p>A l'Assemblée du 16 octobre 1930 il ressort que le nombre des membres actifs est tombé de 71 à 41. La
        crise des années 30 touche aussi notre club, le nombre des actifs diminue à 32 et celui des juniors à
        33.</p>
    <p>La saison 31/32 est une saison très calme, due à l'absence totale de neige jusqu'au mois de mars. En 1933
        sont fêtés les 10 ans du refuge. L'hiver 33/34 fut très enneigée, dès la mi-octobre une importante
        couche de neige couvre les sommets. Le 2 et 12 août, après 4 années d'interruption due à la crise, le
        club renoue avec la tradition en organisant la foire montagnarde au Lac de la Lauch.</p>
</div>

<div class="histoire">
    <img src="../media/numérisation0012.jpg" alt="Foire montagnarde au Lac de la Lauch" width="350" height="250"
        class="right" />
    <h3>1938-1939 : L'agrandissement du refuge.</h3>
    <p>Depuis 1934 année record de la fréquentation du refuge( 1503 personnes y ayant séjourné), on parle
        d'agrandissement...</p>
    <p>Le 12 mai 1938, une Assemblée Générale extraordinaire décide enfin l'agrandissement du refuge.</p>
    <p>Les travaux démarrent sans délai. Tous les travaux sont effectués par les membres et pour le transport de
        matériel, une automobile d'occasion est transformée en camionnette et répond au doux nom de "Rosalie".
    </p>
    <p>Le 27 octobre, lors de l'Assemblée Générale, le but est largement atteint: il ne reste plus que
        l'installation intérieure à terminer. Le 6 août 1939, le nouveau refuge, complètement terminé, est
        inauguré. Le Club a 30 ans...</p>
</div>

<div class="histoire">
    <p>1939-1945: la deuxième Guerre Mondiale.</p>
    <p>Malheureusement, la guerre qui éclate en septembre 1939 interrompt toute activité.</p>
</div>

<div class="histoire">
    <img src="../media/numérisation0011.jpg" alt="Foire montagnarde au Lac de la Lauch" width="350" height="250"
        class="left" />
    <p>En 1940, les membres qui se retrouvent après les évènements de juin continuent à se réunir, soit en ville
        soit au refuge, jusqu'au moment où l'occupant, jugeant notre Président "politish unzuverlässig und
        unwürdig den Verein zu lenken " (politiquement peu sûr et indigne de diriger le club) sous prétexte
        entre autres que nos bulletins d'admission sont encore rédigés en français, le révoque purement et
        simplement.</p>
    <p>Aux réunions se tenant presque chaque semaine, il n'est évidemment que de sport, ce qui a le don de
        mettre hors d'eux les espions dont nous sommes entourés de toutes parts! En 1944 la haine nazie se
        déchaîne envers notre club: cinq membres sont arrêtés et internés au camp de concentration de Schirmeck.
        Heureusement tous sont rentrés, sinon sains, du moins saufs. Certains ont mis des années à se remettre
        des souffrances endurées. Après la Libération de Guebwiller, une première réunion de rescapés a lieu le
        29 mars 1945.</p>
    <p>C'est ainsi que notre Club, après bien des hauts et des bas, a bouclé son demi-siècle d'existence.</p>
</div>

<div class="histoire">
    <h3>De 1946 à nos jours : le Club quinquagénaire poursuit désormais son histoire.</h3>
    <p>Notre refuge ne connaît malheureusement plus l'affluence des samedis d'antan, où nos membres montaient
        par groupes et à pied, bien entendu, depuis Guebwiller, Murbach ou Lautenbach, et y faisaient régner la
        plus joyeuse animation.</p>
    <p>Le recrutement des jeunes devient de plus en plus ardu, concurrencé par des sports plus faciles d'accès,
        dans la vallée. L'esprit d'équipe qui régnait dans notre club a baissé et le feu sacré de la montagne
        s'est refroidi.</p>
    <p>Le ski est en pleine révolution: le métal et le plastique remplacent le bois pour le ski alpin. D'un
        autre côté le ski de fond est à l'abandon. En 1966, les derniers pratiquants sont obligés de traverser
        le Rhin pour s'équiper en Forêt Noire.</p>
    <p>Nos skieurs passent pour des bêtes curieuses sur les crêtes alors désertes...</p>
    <p>En décembre 1967, le Ski Club de Guebwiller transporte la flamme olympique pour les Jeux Olympiques
        d'hiver de Grenoble, du Treh à Ranspach, en pleine nuit dans la solitude de la forêt.</p>
    <p>La fête du 60ème anniversaire se déroule le 5 octobre au Grand-Ballon dans d'excellentes conditions. Un
        grand nombre de jeunes et d'anciens y participe dans la joie, la bonne humeur, et l'amitié.</p>
    <p>Sous l'impulsion de quelques irréductibles membres, notre Club retrouve de la vigueur et reste toujours
        actif. Citons notre participation au déroulement de la coupe du monde, le 12 février 1983, au Markstein,
        nos excursions annuelles, été comme hiver…</p>
    <p>Par ailleurs, nous nous efforçons de garder intact le patrimoine du refuge que nos anciens nous ont
        transmis et qui voit des améliorations constantes, malheureusement parfois fort coûteuses.</p>
    <p>Pendant 10 ans, le Ski-Club Guebwiller organise la Montée du Roedelen, une course à pied de montagne très
        exigeante: 1000m de dénivelé sur le parcours de 11 kilomètres menant de Guebwiller au Roedelen.</p>
    <p>Au cours des années 90, des membres du ski-club Florival nous rejoignent et renforcent l'équipe de ski de
        fond, toujours vaillante. Ses membres participent à de nombreuses compétitions et vont glaner des titres
        de champions de France vétéran, ainsi que des podiums mondiaux vétérans.</p>
    <p>En 2007, le Ski-Club Guebwiller poursuit son désir d'organiser des manifestations, avec sa première
        Marche Nordique du Florival, qui voit la participation de 200 marcheurs.</p>
</div>

